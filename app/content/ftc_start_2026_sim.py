def _t(text: str) -> dict:
    for k, (name, cap) in IMAGES.items():
        text = text.replace(k, _img(name, cap))
    text = text.replace("@@KEYS@@", KEYS).replace("@@SANDBOX@@", SANDBOX)
    for name in ("config", "first-teleop", "builder", "mecanum", "mechanisms", "encoder", "imu", "auto", "match"):
        text = text.replace(f"@@SIM_{name}@@", sim(name))
    return ru(text)


