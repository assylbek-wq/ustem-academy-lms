def q(prompt: str, options: list[str], correct: list[int], why: str) -> dict:
    return {"q": {"ru": prompt}, "options": [{"ru": o} for o in options], "correct": correct, "why": {"ru": why}}


def table(head: list[str], rows: list[tuple]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


