L1_BASICS = ru("""
## Три главные величины

Электрическая цепь похожа на водопровод: батарейка - насос, провода - трубы, а детали - краны и турбины.

| Величина | Обозначение | Единица | Аналогия с водой | Чем измеряют |
|---|---|---|---|---|
| **Напряжение** | U | вольт, В | Давление, которое создает насос | Вольтметр, параллельно детали |
| **Ток** | I | ампер, А (часто миллиампер, мА) | Сколько воды проходит за секунду | Амперметр, в разрыв цепи |
| **Сопротивление** | R | ом, Ом (кОм = 1000 Ом) | Насколько узкая труба | Омметр, деталь без питания |

## Закон Ома

**U = I x R**, а значит **I = U / R** и **R = U / I**.

Пример: к батарейке 9 В подключили резистор 1 кОм. Ток I = 9 / 1000 = 0,009 А = **9 мА**.

Чтобы запомнить, нарисуйте треугольник: U сверху, I и R внизу. Закройте пальцем то, что ищете, и увидите
формулу.

## Цепь должна быть замкнутой

Ток течет только по **замкнутому** пути: от плюса источника через детали к минусу. Разрыв в любом месте
(выключатель, плохой контакт) останавливает ток во всей цепи.

**Короткое замыкание** - когда плюс соединен с минусом без нагрузки. Ток огромный, провода и батарейка
греются. В реальной жизни это опасно, а в лаборатории просто неправильно: всегда проверяйте, что между
плюсом и минусом есть деталь.

## Последовательно и параллельно

| | Последовательно (одна за другой) | Параллельно (рядом, на одних точках) |
|---|---|---|
| Ток | Одинаковый через все детали | Делится между ветками |
| Напряжение | Делится между деталями | Одинаковое на всех ветках |
| Сопротивление резисторов | Складывается: R = R1 + R2 | Меньше меньшего: 1/R = 1/R1 + 1/R2 |

## Как читать принципиальную схему

На схемах детали рисуют условными знаками, а провода - линиями. Точка на пересечении линий означает
соединение, пересечение без точки - провода просто проходят друг над другом.

| Деталь | Как обозначают | Буква на схеме |
|---|---|---|
| Батарейка | Длинная черта (+) и короткая (-) | GB |
| Резистор | Прямоугольник | R |
| Светодиод | Треугольник с чертой и две стрелки наружу | HL или LED |
| Диод | Треугольник с чертой (черта - катод) | VD |
| Кнопка | Разомкнутый контакт с толкателем | SB |
| Транзистор | Круг с базой, коллектором и эмиттером (стрелка на эмиттере) | VT |
| Мотор | Круг с буквой M | M |
| Земля (GND) | Короткие горизонтальные черточки | GND |

Принципиальная схема показывает, **что с чем соединено**, а макетная плата - **где стоят детали**. Одна и
та же схема на макетке может выглядеть по-разному: главное, чтобы совпадали соединения.
""")

