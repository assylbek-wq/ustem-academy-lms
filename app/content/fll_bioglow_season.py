def crit(key: str, title: str, levels: list[str]):
    kk = KA.get(key)
    t = {"ru": title, **({"kk": kk[0]} if kk else {})}
    lv = [{"ru": f"{i + 1} - {x}", **({"kk": f"{i + 1} - {kk[1][i]}"} if kk else {})} for i, x in enumerate(levels)]
    return (t, lv)


